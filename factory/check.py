#!/usr/bin/env python3
"""Acceptance check for one connector package, run by the /factory skill.

Usage:
    python factory/check.py <pkg> --root <checkout dir> [--base origin/main] [--out DIR]

Runs four checks against the checkout at --root and reports every one, even when
an earlier one fails:

1. scope    files changed against --base stay under packages/<pkg>/, the dossier
            docs/_guidebook/providers/<pkg>.md, the generated roster files and uv.lock.
2. verify   make verify PKG=<pkg> (ruff + mypy + pytest + parsimony list --strict).
3. live     pytest packages/<pkg> -m integration, JUnit output. Fails on any failure
            or skip, on zero tests, and on a verb with no passing live test named after
            it (test_<verb> or test_<verb>_...), unless dossier §5 has a line
            "No live test: `<verb>` — <reason>".
4. catalog  packages/<pkg>/scripts/build_catalog.py --save, then the repo's
            scripts/validate_catalog.py against catalog_tests/queries.yaml. Requires
            overall OK, at least one required probe, recall 1.0, and an entry count equal
            to the dossier's "Expected count:" unless a "Count difference:" line is present.
            A package without a build script passes only if dossier §4 says "Strategy: none".

Prints one line per check, writes <out>/report.json plus one log per check, and exits
non-zero if any check fails. Standard library only, so main's copy can run against a
PR checked out in another folder.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET
from dataclasses import asdict, dataclass, field
from pathlib import Path

# Generated by `make readme-roster` (scripts/gen_roster.py).
ROSTER_FILES = ("README.md", "docs/index.md", "connectors.json")
LOCK_FILES = ("uv.lock",)
# Packages whose new registrations need different handling (multi-bundle catalogs,
# one package serving many agencies). Not supported by this MVP.
PROTOCOL_PACKAGES = frozenset({"sdmx"})


@dataclass
class CheckResult:
    name: str
    ok: bool
    summary: str
    details: dict[str, object] = field(default_factory=dict)
    log: str | None = None
    seconds: float = 0.0


# --------------------------------------------------------------------------- helpers


def _env() -> dict[str, str]:
    env = dict(os.environ)
    # uv run must use the --root checkout's own .venv, not the caller's.
    env.pop("VIRTUAL_ENV", None)
    # Hugging Face's Xet transfer stalls behind the cloud-session proxy; plain HTTP downloads work.
    env.setdefault("HF_HUB_DISABLE_XET", "1")
    return env


def _run(cmd: list[str], cwd: Path, log: Path) -> tuple[int, str]:
    """Run *cmd*, tee combined output into *log*, return (exit code, output)."""
    proc = subprocess.run(cmd, cwd=cwd, env=_env(), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    out = proc.stdout or ""
    log.write_text(f"$ {' '.join(cmd)}\n(cwd {cwd})\n\n{out}\nexit {proc.returncode}\n", encoding="utf-8")
    return proc.returncode, out


def _tail(text: str, n: int = 15) -> str:
    return "\n".join(text.strip().splitlines()[-n:])


def _dossier_path(root: Path, pkg: str) -> Path:
    return root / "docs" / "_guidebook" / "providers" / f"{pkg}.md"


def _section(text: str, number: str) -> str:
    """Body of the dossier heading '## <number>.' or '### <number>' up to the next same-level heading."""
    level = "###" if "." in number else "##"
    pattern = rf"^{level} {re.escape(number)}\b.*?$(.*?)(?=^{level} |^## |\Z)"
    m = re.search(pattern, text, flags=re.M | re.S)
    return m.group(1) if m else ""


def _strip_md(s: str) -> str:
    return s.replace("*", "").replace("`", "").strip()


def _expected_count(dossier: str) -> tuple[int | None, str | None]:
    """Return (Expected count, Count difference reason) from dossier §1.4 (whole file as fallback)."""
    body = _section(dossier, "1.4") or dossier
    count: int | None = None
    reason: str | None = None
    for line in body.splitlines():
        clean = _strip_md(line).lstrip("-• ").strip()
        m = re.match(r"Expected count:\s*([0-9][0-9,_ ]*)\s*$", clean, flags=re.I)
        if m and count is None:
            count = int(re.sub(r"[,_ ]", "", m.group(1)))
        m = re.match(r"Count difference:\s*(.+)$", clean, flags=re.I)
        if m and reason is None:
            text = m.group(1).strip()
            if text and not text.startswith("<") and text not in {"___", "-", "none", "n/a"}:
                reason = text
    return count, reason


def _live_exclusions(dossier: str) -> dict[str, str]:
    """Verbs dossier §5 excludes from the live-test rule: 'No live test: `<verb>` — <reason>'."""
    out: dict[str, str] = {}
    for line in _section(dossier, "5").splitlines():
        m = re.match(r"^\W*No live test:\s*`?([A-Za-z0-9_]+)`?\s*(?:[—:-]+\s*(.*))?$", line.strip().replace("**", ""))
        if m:
            out[m.group(1)] = (m.group(2) or "").strip()
    return out


# --------------------------------------------------------------------------- checks


def check_scope(pkg: str, root: Path, base: str, out: Path) -> CheckResult:
    log = out / "scope.log"
    code, mb = _run(["git", "merge-base", base, "HEAD"], root, log)
    if code != 0:
        return CheckResult("scope", False, f"git merge-base {base} HEAD failed", log=str(log))
    mb = mb.strip().splitlines()[-1]
    _, diff = _run(["git", "diff", "--name-only", mb], root, out / "scope-diff.log")
    _, untracked = _run(["git", "ls-files", "--others", "--exclude-standard"], root, out / "scope-untracked.log")
    files = sorted({f for f in (diff + "\n" + untracked).splitlines() if f.strip()})
    allowed_prefix = f"packages/{pkg}/"
    allowed_exact = {f"docs/_guidebook/providers/{pkg}.md", *ROSTER_FILES, *LOCK_FILES}
    outside = [f for f in files if not f.startswith(allowed_prefix) and f not in allowed_exact]
    log.write_text(
        f"base {base} (merge-base {mb})\nchanged:\n" + "\n".join(files) + "\n\noutside scope:\n" + "\n".join(outside),
        encoding="utf-8",
    )
    summary = f"{len(files)} files changed, {len(outside)} outside scope"
    if outside:
        summary += ": " + ", ".join(outside[:10]) + (" …" if len(outside) > 10 else "")
    return CheckResult("scope", not outside, summary, {"changed": files, "outside": outside}, str(log))


def check_verify(pkg: str, root: Path, out: Path) -> CheckResult:
    log = out / "verify.log"
    code, text = _run(["make", "verify", f"PKG={pkg}"], root, log)
    stages = re.findall(r"^==> (.+)$", text, flags=re.M)
    pytest_line = ""
    for line in text.splitlines():
        if re.search(r"=+ .*\b(passed|failed|error)\b.* in [0-9.]+s", line):
            pytest_line = line.strip("= ").strip()
    if code == 0:
        summary = f"ruff ok, mypy ok, pytest {pytest_line or 'ok'}, strict listing ok"
    else:
        stage = stages[-1] if stages else "make"
        summary = f"failed at '{stage}'" + (f" (pytest {pytest_line})" if pytest_line else "")
    return CheckResult(
        "verify", code == 0, summary, {"stages": stages, "pytest": pytest_line, "tail": _tail(text)}, str(log)
    )


def _verbs(pkg: str, root: Path, out: Path) -> list[str] | str:
    code = (
        "import importlib, json; "
        f"m = importlib.import_module('parsimony_{pkg}'); "
        "print('VERBS=' + json.dumps([c.name for c in m.CONNECTORS]))"
    )
    rc, text = _run(["uv", "run", "python", "-c", code], root, out / "verbs.log")
    m = re.search(r"^VERBS=(.*)$", text, flags=re.M)
    if rc != 0 or not m:
        return f"could not import parsimony_{pkg}.CONNECTORS: {_tail(text, 3)}"
    return list(json.loads(m.group(1)))


def _owner(test_name: str, verbs: list[str]) -> str | None:
    """Longest verb V such that the test is named test_V or test_V_... (parametrize suffix ignored)."""
    base = test_name.split("[", 1)[0]
    best = None
    for v in verbs:
        if (base == f"test_{v}" or base.startswith(f"test_{v}_")) and (best is None or len(v) > len(best)):
            best = v
    return best


def check_live(pkg: str, root: Path, out: Path, dossier: str | None) -> CheckResult:
    log = out / "live.log"
    junit = out / "live-junit.xml"
    junit.unlink(missing_ok=True)
    code, text = _run(
        ["uv", "run", "pytest", f"packages/{pkg}", "-m", "integration", "-rs", f"--junitxml={junit}"], root, log
    )
    verbs = _verbs(pkg, root, out)
    if isinstance(verbs, str):
        return CheckResult("live", False, verbs, log=str(log))
    if not junit.exists():
        return CheckResult(
            "live", False, f"pytest wrote no JUnit report (exit {code})", {"tail": _tail(text)}, str(log)
        )

    passed: list[str] = []
    failed: list[str] = []
    skipped: list[str] = []
    for case in ET.parse(junit).getroot().iter("testcase"):
        name = case.get("name", "")
        if case.find("failure") is not None or case.find("error") is not None:
            failed.append(name)
        elif case.find("skipped") is not None:
            skipped.append(name)
        else:
            passed.append(name)

    exclusions = _live_exclusions(dossier or "")
    covered = {v for v in (_owner(t, verbs) for t in passed) if v}
    uncovered = [v for v in verbs if v not in covered and v not in exclusions]
    total = len(passed) + len(failed) + len(skipped)

    problems = []
    if total == 0:
        problems.append("zero live tests")
    if failed:
        problems.append(f"failed: {', '.join(failed[:5])}")
    if skipped:
        reasons = sorted(set(re.findall(r"^SKIPPED \[\d+\] [^:]+:\d+: (.+)$", text, flags=re.M)))
        problems.append("skipped (" + "; ".join(reasons[:3]) + ")" if reasons else "skipped")
    if uncovered:
        problems.append(f"verbs without a passing live test: {', '.join(uncovered)}")

    summary = (
        f"{len(passed)} passed, {len(skipped)} skipped, {len(failed)} failed; {len(covered)}/{len(verbs)} verbs covered"
    )
    if exclusions:
        summary += f", {len(exclusions)} excluded in §5"
    ok = total > 0 and not failed and not skipped and not uncovered
    if not ok:
        summary += " — " + "; ".join(problems)
    details: dict[str, object] = {
        "verbs": verbs,
        "passed": passed,
        "failed": failed,
        "skipped": skipped,
        "covered": sorted(covered),
        "uncovered": uncovered,
        "excluded": exclusions,
        "junit": str(junit),
    }
    return CheckResult("live", ok, summary, details, str(log))


def check_catalog(pkg: str, root: Path, out: Path, dossier: str | None) -> CheckResult:
    log = out / "catalog.log"
    pkg_dir = root / "packages" / pkg
    build = pkg_dir / "scripts" / "build_catalog.py"
    queries = pkg_dir / "catalog_tests" / "queries.yaml"
    dossier_rel = f"docs/_guidebook/providers/{pkg}.md"

    if dossier is None:
        return CheckResult("catalog", False, f"dossier missing: {dossier_rel}")

    if not build.exists():
        strategy = _section(dossier, "4")
        if re.search(r"Strategy:\s*`?none", _strip_md(strategy), flags=re.I):
            return CheckResult("catalog", True, "n/a: no catalog, dossier §4 says Strategy: none (native search)")
        return CheckResult(
            "catalog",
            False,
            f"packages/{pkg}/scripts/build_catalog.py missing and dossier §4 does not say Strategy: none",
        )
    if "--save" not in build.read_text(encoding="utf-8").replace("--save-root", ""):
        return CheckResult(
            "catalog", False, "build_catalog.py has no --save flag (multi-bundle builds are not supported)"
        )
    if not queries.exists():
        return CheckResult("catalog", False, f"packages/{pkg}/catalog_tests/queries.yaml missing")

    expected, difference = _expected_count(dossier)
    snapshot = out / "catalog"
    url = snapshot.resolve().as_uri()
    code, build_out = _run(["uv", "run", "python", str(build.relative_to(root)), "--save", url], root, log)
    if code != 0:
        summary = f"build failed (exit {code}): {_tail(build_out, 1)}"
        if expected is None:
            summary += "; dossier §1.4 has no 'Expected count: <n>' line"
        return CheckResult("catalog", False, summary, {"expected": expected}, str(log))

    vlog = out / "catalog-validate.log"
    vcmd = ["uv", "run", "python", "scripts/validate_catalog.py", "--catalog-url", url, "--queries-file", str(queries)]
    _, vtext = _run(vcmd, root, vlog)
    entries_m = re.search(r"^entry_count: (\d+)$", vtext, flags=re.M)
    recall_m = re.search(r"^required_recall: ([0-9.]+)$", vtext, flags=re.M)
    overall_m = re.search(r"^overall: (\w+)$", vtext, flags=re.M)
    probes = re.findall(r"^  \[(HIT|MISS)( optional)?\] (\S+):", vtext, flags=re.M)
    required = [p for p in probes if not p[1]]
    misses = [p[2] for p in required if p[0] == "MISS"]
    entries = int(entries_m.group(1)) if entries_m else None
    recall = float(recall_m.group(1)) if recall_m else None

    problems = []
    if overall_m is None or entries is None:
        problems.append(f"validation did not run: {_tail(vtext, 2)}")
    elif overall_m.group(1) != "OK":
        problems.append("validation overall FAIL")
    if not required:
        problems.append("no required probes in queries.yaml")
    if misses:
        problems.append(f"required probes missed: {', '.join(misses)}")
    if expected is None:
        problems.append("dossier §1.4 has no 'Expected count: <n>' line")
    elif entries is not None and entries != expected and difference is None:
        problems.append(f"entry count {entries} != Expected count {expected} and no 'Count difference:' line")

    recall_txt = f"{recall:.2f}" if recall is not None else "n/a"
    summary = (
        f"{entries if entries is not None else '?'} entries (expected {expected if expected is not None else '?'}"
        + (f", difference noted: {difference}" if difference and entries != expected else "")
        + f"), recall {recall_txt} on {len(required)} required probes"
    )
    if problems:
        summary += " — " + "; ".join(problems)
    details: dict[str, object] = {
        "entries": entries,
        "expected": expected,
        "count_difference": difference,
        "required_recall": recall,
        "required_probes": len(required),
        "missed": misses,
        "snapshot": url,
        "validate_log": str(vlog),
    }
    return CheckResult("catalog", not problems, summary, details, str(log))


# --------------------------------------------------------------------------- main


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("pkg", help="package directory name under packages/, e.g. fred")
    ap.add_argument("--root", default=".", help="checkout to check (default: current directory)")
    ap.add_argument("--base", default="origin/main", help="git ref the scope check diffs against")
    ap.add_argument("--out", help="directory for report.json, logs and the built catalog (default: a temp dir)")
    args = ap.parse_args(argv)

    pkg = args.pkg.strip().strip("/")
    root = Path(args.root).resolve()
    out = Path(args.out).resolve() if args.out else Path(tempfile.gettempdir()) / "factory-check" / pkg
    out.mkdir(parents=True, exist_ok=True)

    if pkg in PROTOCOL_PACKAGES:
        print(f"check: {pkg} is a protocol package; registrations inside it are not supported yet")
        return 2
    if not (root / "packages" / pkg).is_dir():
        print(f"check: {root}/packages/{pkg} does not exist")
        return 2

    dpath = _dossier_path(root, pkg)
    dossier = dpath.read_text(encoding="utf-8") if dpath.exists() else None

    # Setup: the --root checkout needs its own workspace env, and the kernel next to it.
    setup_notes = []
    if not (root.parent / "parsimony").is_dir():
        setup_notes.append(f"kernel checkout not found at {root.parent / 'parsimony'}")
    code, text = _run(["uv", "sync", "--all-extras", "--all-packages"], root, out / "setup.log")
    if code != 0:
        setup_notes.append(f"uv sync failed: {_tail(text, 2)}")

    results: list[CheckResult] = []
    for name, fn in (
        ("scope", lambda: check_scope(pkg, root, args.base, out)),
        ("verify", lambda: check_verify(pkg, root, out)),
        ("live", lambda: check_live(pkg, root, out, dossier)),
        ("catalog", lambda: check_catalog(pkg, root, out, dossier)),
    ):
        start = time.monotonic()
        try:
            res = fn()
        except Exception as exc:  # report every check, even when one crashes
            res = CheckResult(name, False, f"check crashed: {type(exc).__name__}: {exc}")
        res.seconds = round(time.monotonic() - start, 1)
        results.append(res)

    ok = all(r.ok for r in results) and not setup_notes
    lines = [f"factory check: {pkg} @ {root} (base {args.base})"]
    lines += [f"setup:   FAIL  {n}" for n in setup_notes]
    lines += [f"{r.name + ':':8} {'PASS' if r.ok else 'FAIL'}  {r.summary}" for r in results]
    lines.append(f"overall: {'PASS' if ok else 'FAIL'}")
    report_path = out / "report.json"
    lines.append(f"report:  {report_path}")
    print("\n".join(lines))

    report = {
        "package": pkg,
        "root": str(root),
        "base": args.base,
        "ok": ok,
        "setup": setup_notes,
        "dossier": str(dpath) if dossier is not None else None,
        "checks": [asdict(r) for r in results],
        "summary": "\n".join(lines[:-1]),
    }
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
